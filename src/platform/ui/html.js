// Pure text/attribute escaping for ESM views. Escape ampersands first so input
// entities remain literal text; markup assembly stays with each caller.
export function escapeHtml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}
